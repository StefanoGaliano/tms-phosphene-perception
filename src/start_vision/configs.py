"""sv-configs: eegunify configs per task from configs/template_ds006171.yaml (PHASE1 Step 5).

Fills ``{task}``, ``{subjects}`` (recordings present for the task, from the staged tree or the
inventory) and ``{mapping}`` (``codes.eegunify_mapping()``). A reject rule on
``channels: [eeg]`` is expanded to the 128 EEG channel names (eegunify needs names). For
``noninformative`` the left/right conditions and lateralized contrasts are removed: its Gabor
side is unknown (README decision 6).
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

import pandas as pd
import yaml

from start_vision.codes import TASKS, eegunify_mapping

SIDE_ONLY_CONDITIONS = ("seen_left", "seen_right", "unseen_left", "unseen_right")
LATERAL_CONTRASTS = ("seen_lat", "unseen_lat")


def subjects_for(task: str, inventory: Path) -> list[str]:
    inv = pd.read_csv(inventory, sep="\t", dtype={"subject": str})
    return sorted(inv.loc[inv[task].astype(bool), "subject"])


def render(template: str, task: str, subjects: list[str]) -> dict[str, Any]:
    text = (
        template.replace("{task}", task)
        .replace("{subjects}", json.dumps(subjects))
        .replace("{mapping}", json.dumps(eegunify_mapping()))
    )
    cfg: dict[str, Any] = yaml.safe_load(text)
    eeg = [v for k, v in cfg["channels"]["rename"].items() if re.fullmatch(r"[A-D]\d+", k)]
    for rule in cfg["epochs"]["reject"]["rules"]:
        if rule["channels"] == ["eeg"]:  # eegunify rules need names: expand to the 128 EEG
            rule["channels"] = eeg
    if task == "noninformative":
        for c in SIDE_ONLY_CONDITIONS:
            cfg["conditions"].pop(c)
        for c in LATERAL_CONTRASTS:
            cfg["contrasts"].pop(c)
    return cfg


def write_all(template: Path, inventory: Path, out_dir: Path) -> list[Path]:
    text = template.read_text()
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    for task in TASKS:
        cfg = render(text, task, subjects_for(task, inventory))
        p = out_dir / f"ds006171_{task}.yaml"
        header = (
            f"# GENERATED by sv-configs from {template.name}; do not edit by hand.\n"
            f"# Task {task}: {len(cfg['recordings']['subjects'])} subjects.\n"
        )
        if task == "noninformative":
            header += "# No left/right conditions or lateralized contrasts (README decision 6).\n"
        p.write_text(header + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, width=100))
        paths.append(p)
    return paths
